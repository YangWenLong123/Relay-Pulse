import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import dotenv from 'dotenv';

export const PACKAGED_ENV_FILE = '.env';
export const PACKAGED_ENV_EXAMPLE_FILE = '.env.example';

// These settings affect how the local service runs, but do not contain account
// data or encryption material. Secrets must be entered beside the executable.
const BUNDLED_KEYS = [
  'SERVER_PORT',
  'SERVER_HOST',
  'CLIENT_ORIGIN',
  'ALLOW_EXTENSION_ORIGINS',
  'DATA_DIR',
  'HISTORY_LIMIT',
  'POOL_USAGE_LIMIT',
  'CODEX_USAGE_LIMIT',
  'BATCH_CONCURRENCY',
  'CODEX_UPSTREAM_BASE_URL',
  'CODEX_UPSTREAM_PROXY_URL',
  'CODEX_CLIENT_VERSION',
  'CC_SWITCH_DB_PATH'
];

const SECRET_KEYS = new Set([
  'API_KEY_ENCRYPTION_SECRET',
  'ACCOUNT_SESSION_ENCRYPTION_SECRET',
  'EXTENSION_ACCESS_TOKEN'
]);

const URL_KEYS = new Set([
  'CODEX_UPSTREAM_BASE_URL',
  'CODEX_UPSTREAM_PROXY_URL'
]);

function formatValue(value) {
  return JSON.stringify(value);
}

function canBundleValue(key, value) {
  if (SECRET_KEYS.has(key)) return false;
  if (!URL_KEYS.has(key)) return true;
  try {
    const url = new URL(value);
    if (url.username || url.password) return false;
    return key !== 'CODEX_UPSTREAM_PROXY_URL' || (url.protocol === 'http:' || url.protocol === 'https:');
  } catch {
    return key !== 'CODEX_UPSTREAM_PROXY_URL';
  }
}

export function selectBundledEnvironment(source = '') {
  const parsed = dotenv.parse(source);
  const values = [];
  const excludedKeys = [];

  for (const key of SECRET_KEYS) {
    if (parsed[key]?.trim()) excludedKeys.push(key);
  }

  for (const key of BUNDLED_KEYS) {
    const value = parsed[key]?.trim();
    if (!value) continue;
    if (!canBundleValue(key, value)) {
      excludedKeys.push(key);
      continue;
    }
    values.push(`${key}=${formatValue(value)}`);
  }

  return { values, excludedKeys };
}

export function renderBundledEnvironment(source = '') {
  const { values, excludedKeys } = selectBundledEnvironment(source);
  return {
    content: [
      '# Generated by scripts/package-server.mjs.',
      '# Only non-secret runtime settings are copied from the build environment.',
      ...values,
      ''
    ].join('\n'),
    excludedKeys
  };
}

export function renderEnvironmentExample() {
  return `# Runtime configuration for relay-pulse-start.
# This file is safe to edit. Rename/copy it to .env beside the executable.

SERVER_PORT=3100
SERVER_HOST=127.0.0.1
CLIENT_ORIGIN=http://localhost:5173,http://127.0.0.1:5173
ALLOW_EXTENSION_ORIGINS=true

# The packaged service stores data in the operating system application data directory by default.
# DATA_DIR=./data

CODEX_UPSTREAM_BASE_URL=https://chatgpt.com/backend-api/codex
# Set this when ChatGPT cannot be reached directly.
CODEX_UPSTREAM_PROXY_URL=
CODEX_CLIENT_VERSION=0.145.0

# Optional local limits.
# HISTORY_LIMIT=1000
# POOL_USAGE_LIMIT=10000
# CODEX_USAGE_LIMIT=10000
# BATCH_CONCURRENCY=4
# CC_SWITCH_DB_PATH=~/.cc-switch/cc-switch.db

# Keep encryption secrets out of distributable packages. Add them manually to .env if needed.
# API_KEY_ENCRYPTION_SECRET=
# ACCOUNT_SESSION_ENCRYPTION_SECRET=

# Native Messaging generates this automatically on first launch. Do not share it.
# EXTENSION_ACCESS_TOKEN=
`;
}

export async function writePackagedRuntimeConfig(outputDir, source = '') {
  const bundled = renderBundledEnvironment(source);
  await writeFile(path.join(outputDir, PACKAGED_ENV_FILE), bundled.content, 'utf8');
  await writeFile(path.join(outputDir, PACKAGED_ENV_EXAMPLE_FILE), renderEnvironmentExample(), 'utf8');
  return bundled;
}
